function normalize(input: string): string {
  return input.trim().toLowerCase().replace(/\s+/g, ' ');
}

export function findKingLegacyItem(query: string): KingLegacyItem | undefined {
  const q = normalize(query);
  if (!q) return undefined;

  const exact = KING_LEGACY_ITEMS.find(
    (item) =>
      normalize(item.name) === q ||
      item.id === q ||
      item.aliases.some((alias) => normalize(alias) === q),
  );
  if (exact) return exact;

  const prefix = KING_LEGACY_ITEMS.find(
    (item) =>
      normalize(item.name).startsWith(q) ||
      item.aliases.some((alias) => normalize(alias).startsWith(q)),
  );
  if (prefix) return prefix;

  return KING_LEGACY_ITEMS.find(
    (item) =>
      normalize(item.name).includes(q) ||
      item.aliases.some((alias) => normalize(alias).includes(q)),
  );
}

export function searchKingLegacyItems(query: string, limit = 25): KingLegacyItem[] {
  const q = normalize(query);
  if (!q) return KING_LEGACY_ITEMS.slice(0, limit);

  const startsWithMatches: KingLegacyItem[] = [];
  const containsMatches: KingLegacyItem[] = [];

  for (const item of KING_LEGACY_ITEMS) {
    const name = normalize(item.name);
    const aliasStarts = item.aliases.some((a) => normalize(a).startsWith(q));
    const aliasContains = item.aliases.some((a) => normalize(a).includes(q));

    if (name.startsWith(q) || aliasStarts) {
      startsWithMatches.push(item);
    } else if (name.includes(q) || aliasContains) {
      containsMatches.push(item);
    }
  }

  return [...startsWithMatches, ...containsMatches].slice(0, limit);
}

export function formatValueResponse(item: KingLegacyItem): string {
  const itemLabel = item.emoji ? `${item.emoji} ${item.name}` : item.name;
  if (item.forOneFin && item.forOneFin > 1) {
    return `**${item.forOneFin}x ${itemLabel}** is worth  ≈ **1x** ${SK_FIN_EMOJI}`;
  }
  return `**${itemLabel}** is worth  ≈ **${item.value}x** ${SK_FIN_EMOJI}`;
}
